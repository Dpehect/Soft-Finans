interface I18nStore {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
}

export const useI18nStore = create<I18nStore>()(
  persist(
    (set) => ({
      language: "tr",
      setLanguage: (language: LanguageCode) => set({ language }),
    }),
    {
      name: "sb_finans_language",
    },
  ),
);

export function useTranslation() {
  const language = useI18nStore((s) => s.language);
  const setLanguage = useI18nStore((s) => s.setLanguage);

  const t = (key: string, fallback?: string): string => {
    return TRANSLATIONS[language]?.[key] ?? TRANSLATIONS["tr"]?.[key] ?? fallback ?? key;
  };

  return {
    t,
    language,
    setLanguage,
    languages: SUPPORTED_LANGUAGES,
    currentMeta: SUPPORTED_LANGUAGES.find((l) => l.code === language) ?? SUPPORTED_LANGUAGES[0],
  };
}
